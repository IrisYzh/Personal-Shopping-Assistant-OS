"""Write sample emails for extension/preview.html from the real templates in digest.py.

Run after editing digest.py:  python -m shopping_agent preview-emails
"""

from __future__ import annotations

import json
import tempfile
from pathlib import Path

from .digest import build_weekly_digest, instant_alert
from .models import Availability
from .server import ShoppingApi


class _NoSheets:
    enabled = False


def sample_emails() -> list[dict[str, str]]:
    with tempfile.TemporaryDirectory() as directory:
        api = ShoppingApi(directory, pilot_keys={}, sheets=_NoSheets())
        align = {
            "name": 'Align High-Rise Pant 25"',
            "url": "https://shop.lululemon.com/p/women-pants/Align-Pant-2/_/prod2020012",
            "price": 98, "currency": "USD", "availability": "out_of_stock", "confidence": 0.95,
        }
        bra = {
            "name": "Fits Everybody T-Shirt Bra",
            "url": "https://skims.com/products/fits-everybody-t-shirt-bra",
            "price": 48, "currency": "USD", "availability": "in_stock", "confidence": 0.95,
        }
        blush = {
            "name": "Rare Beauty Soft Pinch Liquid Blush",
            "url": "https://www.sephora.com/product/soft-pinch-liquid-blush-P97989778",
            "price": 23, "currency": "USD", "availability": "in_stock", "confidence": 0.95,
        }
        when = "2026-11-10T10:00:00+00:00"
        ids = []
        for product, event in ((align, "add_to_cart"), (bra, "add_to_wishlist"), (blush, "add_to_wishlist")):
            item = api.record_event("me", {"event_type": event, "session_id": "s", "occurred_at": when, "product": product})["item"]
            ids.append(item["id"])
        api.update_item("me", ids[0], {"size": "6", "color": "Black"})
        api.update_item("me", ids[1], {"size": "34B", "color": "Clay"})
        repo = api.context("me").repository

        # What a real price and stock check would leave behind.
        align_item = repo.get_item(ids[0])
        align_item.last_price, align_item.last_availability = 69.0, Availability.IN_STOCK
        repo.save_item(align_item)
        bra_item = repo.get_item(ids[1])
        bra_item.last_promotion = "Sitewide 20% off through Sunday"
        repo.save_item(bra_item)
        alerts = [
            {"item_id": ids[0], "type": "restock", "old_price": 98, "new_price": 98, "size": "6", "created_at": "2026-11-12T08:00:00+00:00"},
            {"item_id": ids[0], "type": "price_drop", "old_price": 98, "new_price": 69, "created_at": "2026-11-13T08:00:00+00:00"},
            {"item_id": ids[1], "type": "promotion", "old_price": 48, "new_price": 48, "promotion_text": "Sitewide 20% off through Sunday", "created_at": "2026-11-13T09:00:00+00:00"},
        ]
        for index, alert in enumerate(alerts):
            repo.append_alert({**alert, "id": f"a{index}", "availability": "in_stock", "dedupe_key": f"a{index}"})

        emails = []
        digest = build_weekly_digest(repo, now="2026-11-14T09:00:00+00:00")
        if digest:
            emails.append({"kind": "Weekly digest, Saturday 9 AM", "subject": digest.subject, "body": digest.body, "html": digest.html})
        restock = instant_alert(repo.get_item(ids[0]), alerts[0])
        if restock:
            emails.append({"kind": "Instant alert, size back in stock", "subject": restock.subject, "body": restock.body, "html": restock.html})
        drop = instant_alert(repo.get_item(ids[0]), alerts[1])
        if drop:
            emails.append({"kind": "Instant alert, price drop", "subject": drop.subject, "body": drop.body, "html": drop.html})
        sale = instant_alert(repo.get_item(ids[1]), alerts[2])
        if sale:
            emails.append({"kind": "Instant alert, sale started", "subject": sale.subject, "body": sale.body, "html": sale.html})
        return emails


def write_preview_emails(path: str | Path = "extension/preview-emails.js") -> Path:
    path = Path(path)
    data = json.dumps(sample_emails(), ensure_ascii=False, indent=2)
    path.write_text(
        "// Generated by `python -m shopping_agent preview-emails` from shopping_agent/digest.py.\n"
        "// Do not edit by hand. Edit digest.py, then run the command again.\n"
        f"window.PREVIEW_EMAILS = {data};\n",
        encoding="utf-8",
    )
    return path
